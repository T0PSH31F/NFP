#!/usr/bin/env python3
"""
Jarvis Enterprise Zero-Touch Customer Provisioning Engine
=========================================================
Ingests `intake.json` and generates a complete multi-tenant customer profile
inside `jarvis-fleet` (`customers/<slug>/`):
  1. `configuration.nix` with declarative white-labeling (`jarvis.branding`),
     role quotas, deployment target (`bare-metal-iso`, `proxmox-qcow2`, `podman-stack`),
     and Litestream SQLite WAL backup target.
  2. `secrets.yaml` SOPS-Nix encrypted secrets manifest.
  3. `docker-compose.yml` for Podman/Docker appliance stack deployments.
  4. `litestream.yml` for continuous SQLite WAL replication to NAS/S3.
"""

import argparse
import json
import re
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict


def slugify(value: str) -> str:
    clean = re.sub(r"[^a-zA-Z0-9]+", "-", value.strip().lower()).strip("-")
    return clean or "customer-org"


def provision_customer_profile(intake: Dict[str, Any], fleet_dir: Path) -> Dict[str, Any]:
    customer_name = str(intake.get("customer_name", "Acme Services Corp")).strip()
    slug = str(intake.get("customer_slug") or slugify(customer_name))
    target = str(intake.get("deployment_target", "proxmox-qcow2"))
    desktop = str(intake.get("desktop_choice", "headless"))
    branding = intake.get("branding", {})
    product_name = str(branding.get("product_name", f"{customer_name} AI Manager"))
    primary_color = str(branding.get("primary_color", "#0A2540"))
    support_contact = str(branding.get("support_contact", f"support@{slug}.com"))
    persona_name = str(branding.get("persona_name", f"{customer_name} Concierge"))
    backup_url = str(intake.get("backup_replica_url", f"file:///mnt/nas/backups/{slug}"))
    monthly_fee = float(intake.get("monthly_fee_usd", 499.0))

    cust_dir = fleet_dir / slug
    cust_dir.mkdir(parents=True, exist_ok=True)

    # 1. NixOS Customer Configuration
    config_nix = f"""# Auto-generated by provision_customer.py for {customer_name} ({slug})
{{
  config,
  lib,
  pkgs,
  ...
}}:
{{
  jarvis = {{
    enable = true;
    customerName = "{customer_name}";
    customerSlug = "{slug}";
    desktopChoice = "{desktop}";
    deploymentTarget = "{target}";

    branding = {{
      enable = true;
      productName = "{product_name}";
      logoPath = null;
      primaryColor = "{primary_color}";
      supportContact = "{support_contact}";
      personaName = "{persona_name}";
    }};

    backup = {{
      enable = true;
      replicaUrl = "{backup_url}";
      monthlyFeeUsd = {monthly_fee};
    }};
  }};

  layers.layer-10.system.config.security-hardening.enable = true;
  networking.hostName = lib.mkDefault "jarvis-{slug}";
  system.stateVersion = lib.mkDefault "25.05";
}}
"""
    config_path = cust_dir / "configuration.nix"
    config_path.write_text(config_nix, encoding="utf-8")

    # 2. SOPS Secrets Manifest
    secrets_path = cust_dir / "secrets.yaml"
    secrets_path.write_text(
        f"""# SOPS-Nix Secrets for {customer_name} ({slug})
customer_slug: "{slug}"
extremerouter_jwt_secret: "ENC[AES256_GCM,data:sops-jwt-{slug},type:str]"
langfuse_api_key: "ENC[AES256_GCM,data:sops-lf-{slug},type:str]"
sops:
  version: "3.9.0"
""",
        encoding="utf-8",
    )

    # 3. Litestream SQLite WAL Replication Config
    litestream_path = cust_dir / "litestream.yml"
    litestream_path.write_text(
        f"""dbs:
  - path: /var/lib/jarvis/state.sqlite
    replicas:
      - url: {backup_url}/state.sqlite
        sync-interval: 10s
  - path: /var/lib/jarvis/rag_hybrid.sqlite
    replicas:
      - url: {backup_url}/rag_hybrid.sqlite
        sync-interval: 30s
""",
        encoding="utf-8",
    )

    # 4. Podman / Docker Compose Stack (Target 3)
    compose_path = cust_dir / "docker-compose.yml"
    compose_path.write_text(
        f"""version: "3.9"
services:
  extremerouter:
    image: docker.io/rsalmn/extremerouter:latest
    container_name: jarvis-{slug}-router
    ports:
      - "20128:20128"
    environment:
      ENABLE_RTK: "true"
      ENABLE_HEADROOM: "true"
      ENABLE_CAVEMAN: "true"
    volumes:
      - jarvis_state:/var/lib/jarvis
    restart: unless-stopped

  jev-proxy:
    image: python:3.12-slim
    container_name: jarvis-{slug}-jev
    ports:
      - "20127:20127"
    volumes:
      - jarvis_state:/var/lib/jarvis
    restart: unless-stopped

volumes:
  jarvis_state:
""",
        encoding="utf-8",
    )

    manifest = {
        "status": "provisioned",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "customer_name": customer_name,
        "customer_slug": slug,
        "deployment_target": target,
        "files_created": [
            str(config_path),
            str(secrets_path),
            str(litestream_path),
            str(compose_path),
        ],
    }
    (cust_dir / "provision_manifest.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )
    return manifest


def self_test() -> int:
    print("==> Running Zero-Touch Customer Provisioning Engine Self-Test...")
    with tempfile.TemporaryDirectory() as tmpdir:
        intake = {
            "customer_name": "Starlight Logistics LLC",
            "deployment_target": "proxmox-qcow2",
            "desktop_choice": "headless",
            "branding": {
                "product_name": "Starlight Dispatch AI",
                "primary_color": "#1E3A8A",
                "support_contact": "it@starlight.io",
                "persona_name": "Starlight Ops",
            },
            "monthly_fee_usd": 1000.0,
        }
        res = provision_customer_profile(intake, Path(tmpdir))
        assert res["customer_slug"] == "starlight-logistics-llc"
        for fpath in res["files_created"]:
            assert Path(fpath).exists(), f"Missing generated file: {fpath}"
        cfg_text = Path(res["files_created"][0]).read_text(encoding="utf-8")
        assert 'productName = "Starlight Dispatch AI";' in cfg_text
        print("  [PASS] Customer Nix profile + SOPS secrets + Litestream WAL + Podman stack generated")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Jarvis Customer Provisioning Engine")
    parser.add_argument("--test", action="store_true", help="Run self-test")
    parser.add_argument("--intake", type=str, help="Path to intake.json or inline JSON")
    parser.add_argument("--fleet-dir", type=str, default="customers", help="Target customers directory")
    args = parser.parse_args()

    if args.test:
        return self_test()

    if args.intake:
        p = Path(args.intake)
        intake_data = json.loads(p.read_text(encoding="utf-8")) if p.exists() else json.loads(args.intake)
    else:
        intake_data = {"customer_name": "Acme Services Corp"}

    res = provision_customer_profile(intake_data, Path(args.fleet_dir))
    print(json.dumps(res, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
