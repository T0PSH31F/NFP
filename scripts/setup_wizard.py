#!/usr/bin/env python3
"""
Jarvis Enterprise First-Time Setup Concierge & Guided Onboarding Wizard
=======================================================================
Conducts the 4-question discovery interview (business role, ingress channels,
desired automation swarms, support tier), auto-selects required Jarvis skills,
generates encrypted-ready SOPS `secrets.yaml` and `.env` manifests, and emits
the inaugural Command Center tour payload.
"""

import argparse
import json
import os
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List


CHANNEL_TO_SKILLS = {
    "twilio": ["call-agent-booking", "sms-lead-responder"],
    "telnyx": ["call-agent-booking", "sms-lead-responder"],
    "slack": ["slack-socket-triage", "incident-escalator"],
    "discord": ["discord-community-concierge"],
    "matrix": ["matrix-e2ee-bridge"],
    "desktop-voice": ["duplex-voice-chamber", "silero-vad-barge-in"],
}

SWARM_TO_MODULES = {
    "oncall": "jarvis.agents.oncall",
    "news-curator": "jarvis.agents.newsCurator",
    "task-watcher": "jarvis.agents.taskWatcher",
    "ui-replicator": "jarvis.skills.uiReplicator",
    "damage-control": "jarvis.core.damageControl",
    "email-triage": "jarvis.emailTriage",
}


def generate_onboarding_bundle(
    answers: Dict[str, Any], output_dir: Path
) -> Dict[str, Any]:
    """
    Processes the 4 discovery interview answers:
      1. business_role / organization_name
      2. channels (list of ingress channels)
      3. swarms (list of desired autonomous swarms)
      4. support_tier (standard / enterprise-sla / rack-a-month)
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    org_name = str(answers.get("organization_name", "Acme Services")).strip()
    slug = org_name.lower().replace(" ", "-").replace("_", "-")
    role = str(answers.get("business_role", "smb-owner")).strip()
    channels: List[str] = list(answers.get("channels", ["twilio", "slack", "desktop-voice"]))
    swarms: List[str] = list(
        answers.get("swarms", ["oncall", "news-curator", "task-watcher", "damage-control"])
    )
    support_tier = str(answers.get("support_tier", "enterprise-sla")).strip()

    selected_skills: List[str] = []
    for ch in channels:
        for sk in CHANNEL_TO_SKILLS.get(ch.lower(), []):
            if sk not in selected_skills:
                selected_skills.append(sk)

    enabled_modules = [SWARM_TO_MODULES[s] for s in swarms if s in SWARM_TO_MODULES]

    # 1. Generate SOPS-ready secrets.yaml template
    secrets_yaml_path = output_dir / "secrets.yaml"
    secrets_content = f"""# SOPS-Nix Encrypted Secrets Manifest for {org_name} ({slug})
# Generated by Jarvis Setup Concierge at {datetime.now(timezone.utc).isoformat()}
jarvis_customer_slug: "{slug}"
extremerouter_jwt_secret: "ENC[AES256_GCM,data:sops-managed-jwt,type:str]"
twilio_auth_token: "ENC[AES256_GCM,data:sops-managed-twilio,type:str]"
slack_bot_token: "ENC[AES256_GCM,data:sops-managed-slack,type:str]"
langfuse_secret_key: "ENC[AES256_GCM,data:sops-managed-langfuse,type:str]"
sops:
  version: "3.9.0"
  encrypted_regex: "^(extremerouter_jwt_secret|twilio_auth_token|slack_bot_token|langfuse_secret_key)$"
"""
    secrets_yaml_path.write_text(secrets_content, encoding="utf-8")

    # 2. Generate .env configuration for local container/runtime bindings
    env_path = output_dir / ".env.sops"
    env_content = "\n".join(
        [
            f"JARVIS_CUSTOMER_NAME=\"{org_name}\"",
            f"JARVIS_CUSTOMER_SLUG=\"{slug}\"",
            f"JARVIS_BUSINESS_ROLE=\"{role}\"",
            f"JARVIS_SUPPORT_TIER=\"{support_tier}\"",
            f"JARVIS_INGRESS_CHANNELS=\"{','.join(channels)}\"",
            f"JARVIS_ENABLED_SKILLS=\"{','.join(selected_skills)}\"",
            "JEV_PROXY_URL=\"http://127.0.0.1:20127\"",
            "EXTREMEROUTER_URL=\"http://127.0.0.1:20128\"",
            "PWA_COMMAND_CENTER_URL=\"http://127.0.0.1:8096\"",
        ]
    ) + "\n"
    env_path.write_text(env_content, encoding="utf-8")

    # 3. Generate Inaugural Tour & Concierge Summary JSON
    summary = {
        "status": "onboarded",
        "organization_name": org_name,
        "customer_slug": slug,
        "business_role": role,
        "support_tier": support_tier,
        "channels_configured": channels,
        "selected_skills": selected_skills,
        "enabled_modules": enabled_modules,
        "secrets_yaml": str(secrets_yaml_path),
        "env_file": str(env_path),
        "inaugural_ptt_greeting": (
            f"Welcome to {org_name} AI Command Center. Jev System-1 pre-flight protection, "
            f"{len(selected_skills)} skills, and {len(enabled_modules)} proactive agent swarms are online."
        ),
        "command_center_url": "http://127.0.0.1:8096",
    }
    (output_dir / "concierge_summary.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8"
    )
    return summary


def self_test() -> int:
    print("==> Running First-Time Setup Concierge Self-Test...")
    with tempfile.TemporaryDirectory() as tmpdir:
        sample_answers = {
            "organization_name": "Apex HVAC & Plumbing",
            "business_role": "field-services-owner",
            "channels": ["twilio", "slack", "desktop-voice"],
            "swarms": ["oncall", "task-watcher", "damage-control", "email-triage"],
            "support_tier": "rack-a-month",
        }
        res = generate_onboarding_bundle(sample_answers, Path(tmpdir))
        assert res["customer_slug"] == "apex-hvac-&-plumbing" or "apex" in res["customer_slug"]
        assert "call-agent-booking" in res["selected_skills"]
        assert Path(res["secrets_yaml"]).exists()
        assert Path(res["env_file"]).exists()
        print("  [PASS] 4-question discovery interview + SOPS secrets.yaml + skill linking verified")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Jarvis First-Time Setup Concierge Wizard")
    parser.add_argument("--test", action="store_true", help="Run self-test suite")
    parser.add_argument("--answers-json", type=str, help="JSON string or file path with interview answers")
    parser.add_argument("--out-dir", type=str, default="/tmp/jarvis-onboarding", help="Output directory")
    args = parser.parse_args()

    if args.test:
        return self_test()

    if args.answers_json:
        p = Path(args.answers_json)
        data = json.loads(p.read_text(encoding="utf-8")) if p.exists() else json.loads(args.answers_json)
    else:
        data = {
            "organization_name": "Acme Services",
            "business_role": "executive",
            "channels": ["twilio", "slack", "matrix", "desktop-voice"],
            "swarms": ["oncall", "news-curator", "task-watcher", "damage-control"],
            "support_tier": "enterprise-sla",
        }

    summary = generate_onboarding_bundle(data, Path(args.out_dir))
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
