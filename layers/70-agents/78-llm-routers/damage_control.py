#!/usr/bin/env python3
"""
NFP Jev Damage Control & Command Safety Guard
==============================================
Command inspection middleware intercepting bash and system execution requests
generated by agents before execution. Enforces deterministic safety policies
blocking destructive actions (rm -rf, raw disk writes, unverified git force pushes,
dd, mkfs, unsafe nix-store --gc) unless authorized by an explicit, 1-tap user
override via an A2UI Action Card.

Part of dendritic layer: layers/70-agents/78-llm-routers/
"""

import sys
import os
import re
import json
import uuid
import sqlite3
import shlex
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

REPO_ROOT = Path(__file__).resolve().parents[3]
AUDIT_DB_PATH = Path(os.environ.get("DAMAGE_CONTROL_DB", Path.home() / ".local/share/jarvis/command_audit.sqlite"))

# Destructive patterns that strictly require 1-tap override
DESTRUCTIVE_RULES = [
    {
        "id": "root-rm-rf",
        "pattern": r"(?:^|\s|;)rm\s+-[a-zA-Z]*r[a-zA-Z]*f[a-zA-Z]*\s+(?:/|\*|~|/home|/etc|/boot|/var|/nix|/persist)",
        "severity": "critical",
        "description": "Recursive forced deletion of root or critical filesystem paths",
    },
    {
        "id": "raw-disk-write-dd",
        "pattern": r"(?:^|\s|;)dd\s+.*of=/dev/(?:nvme[0-9]n[0-9]|sd[a-z]|vd[a-z]|loop[0-9]|mapper)",
        "severity": "critical",
        "description": "Raw disk or block device write using dd",
    },
    {
        "id": "disk-format-mkfs",
        "pattern": r"(?:^|\s|;)(?:mkfs\.[a-z0-9]+|wipefs|parted|fdisk|gdisk|sgdisk)\s+.*(?:/dev/)",
        "severity": "critical",
        "description": "Filesystem formatting or destructive disk partitioning",
    },
    {
        "id": "git-force-push",
        "pattern": r"(?:^|\s|;)git\s+push\s+.*(?:--force|-f\b)",
        "severity": "high",
        "description": "Git force push risking upstream commit history destruction",
    },
    {
        "id": "unsafe-nix-gc",
        "pattern": r"(?:^|\s|;)nix-store\s+--gc",
        "severity": "critical",
        "description": "Unsafe nix-store --gc violates recovery.md rule (destroys util-linux boot metadata)",
    },
    {
        "id": "global-pkill-nix",
        "pattern": r"(?:^|\s|;)(?:pkill|killall)\s+(?:-9\s+)?nix",
        "severity": "high",
        "description": "Global nix process termination violates nix-resource-safety.md",
    },
    {
        "id": "direct-cryptsetup-erase",
        "pattern": r"(?:^|\s|;)cryptsetup\s+(?:erase|luksFormat|luksKillSlot)",
        "severity": "critical",
        "description": "Destructive LUKS encryption header manipulation",
    }
]

class DamageControlGuard:
    def __init__(self, db_path: Path = AUDIT_DB_PATH):
        self.db_path = db_path
        self._init_db()

    def _init_db(self):
        try:
            self.db_path.parent.mkdir(parents=True, exist_ok=True)
            with sqlite3.connect(str(self.db_path)) as conn:
                conn.execute("""
                CREATE TABLE IF NOT EXISTS command_audit (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    timestamp TEXT NOT NULL,
                    agent_id TEXT NOT NULL,
                    command TEXT NOT NULL,
                    verdict TEXT NOT NULL,
                    rule_id TEXT,
                    severity TEXT NOT NULL,
                    reason TEXT NOT NULL,
                    override_card_id TEXT,
                    override_approved INTEGER DEFAULT 0
                );
                """)
                conn.execute("""
                CREATE TABLE IF NOT EXISTS active_overrides (
                    card_id TEXT PRIMARY KEY,
                    command_hash TEXT NOT NULL,
                    command TEXT NOT NULL,
                    approved INTEGER NOT NULL,
                    created_at TEXT NOT NULL,
                    expires_at TEXT NOT NULL
                );
                """)
                conn.commit()
        except Exception as e:
            sys.stderr.write(f"Warning: Could not initialize command audit SQLite DB: {e}\n")

    def inspect_command(self, cmd_str: str, agent_id: str = "unknown") -> Dict[str, Any]:
        """
        Inspects a system command before execution.
        Returns evaluation dict with 'allowed', 'verdict', 'severity', and optional 'a2ui_card'.
        """
        clean_cmd = cmd_str.strip()
        now_iso = datetime.now(timezone.utc).isoformat()

        # Check for matched destructive rules
        for rule in DESTRUCTIVE_RULES:
            if re.search(rule["pattern"], clean_cmd, re.I):
                card_id = f"card-sec-{uuid.uuid4().hex[:10]}"
                a2ui_card = {
                    "card_id": card_id,
                    "timestamp": now_iso,
                    "source_agent": "damage-control-guard",
                    "target_persona": "glados-auditor",
                    "title": f"🛑 BLOCKED DESTRUCTIVE COMMAND [{rule['severity'].upper()}]: {rule['id']}",
                    "summary": f"Agent '{agent_id}' requested a high-risk operation: {rule['description']}. Command was safely halted.",
                    "risk_level": rule["severity"],
                    "verdict": "DISPATCH_AGENT",
                    "actionability": True,
                    "diff_preview": {
                        "file_path": "CLI Bash Execution",
                        "old_content": "# Blocked command invocation\n" + clean_cmd,
                        "new_content": "# Requires manual override token",
                        "unified_diff": f"--- blocked_command\n+++ approved_override\n- {clean_cmd}\n+ [AWAITING USER 1-TAP OVERRIDE]"
                    },
                    "actions": [
                        {
                            "id": "act-override-approve",
                            "label": "Authorize Override (1-Tap)",
                            "style": "danger",
                            "action_type": "approve",
                            "payload": {
                                "card_id": card_id,
                                "command": clean_cmd,
                                "rule_id": rule["id"]
                            }
                        },
                        {
                            "id": "act-abort-command",
                            "label": "Abort & Block",
                            "style": "primary",
                            "action_type": "dismiss",
                            "payload": {"card_id": card_id}
                        }
                    ],
                    "ttl_rule": {
                        "timeout_seconds": 180,
                        "default_action_id": "act-abort-command",
                        "on_expire": "auto_dismiss"
                    }
                }

                # Log to SQLite
                self._log_audit(agent_id, clean_cmd, "BLOCKED", rule["id"], rule["severity"], rule["description"], card_id)

                return {
                    "allowed": False,
                    "verdict": "BLOCKED",
                    "rule_id": rule["id"],
                    "severity": rule["severity"],
                    "description": rule["description"],
                    "a2ui_card": a2ui_card
                }

        # Safe command
        self._log_audit(agent_id, clean_cmd, "ALLOWED", None, "low", "Clean command passed safety verification", None)
        return {
            "allowed": True,
            "verdict": "ALLOWED",
            "rule_id": None,
            "severity": "low",
            "description": "Command passed safety filters"
        }

    def _log_audit(self, agent_id: str, cmd: str, verdict: str, rule_id: Optional[str], severity: str, reason: str, card_id: Optional[str]):
        try:
            with sqlite3.connect(str(self.db_path)) as conn:
                conn.execute("""
                INSERT INTO command_audit (timestamp, agent_id, command, verdict, rule_id, severity, reason, override_card_id)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?);
                """, (
                    datetime.now(timezone.utc).isoformat(),
                    agent_id,
                    cmd[:1000],
                    verdict,
                    rule_id,
                    severity,
                    reason[:500],
                    card_id
                ))
                conn.commit()
        except Exception:
            pass

    def approve_override(self, card_id: str) -> bool:
        """Approves a blocked command via card ID."""
        try:
            with sqlite3.connect(str(self.db_path)) as conn:
                conn.execute("""
                UPDATE command_audit SET override_approved = 1 WHERE override_card_id = ?;
                """, (card_id,))
                conn.commit()
                return True
        except Exception:
            return False

def self_test() -> int:
    print("==> Running Damage Control & Command Safety Guard Self-Test...")
    test_db = Path("/tmp/test_damage_control.sqlite")
    if test_db.exists():
        test_db.unlink()

    guard = DamageControlGuard(db_path=test_db)

    # 1. Test destructive command blocks
    critical_tests = [
        ("rm -rf /", "root-rm-rf"),
        ("rm -rf /home/t0psh31f/Clan", "root-rm-rf"),
        ("dd if=/dev/zero of=/dev/nvme0n1 bs=1M", "raw-disk-write-dd"),
        ("mkfs.ext4 /dev/sda1", "disk-format-mkfs"),
        ("git push origin main --force", "git-force-push"),
        ("nix-store --gc", "unsafe-nix-gc"),
        ("pkill -9 nix", "global-pkill-nix")
    ]

    for cmd, expected_rule in critical_tests:
        res = guard.inspect_command(cmd, agent_id="test-agent")
        assert res["allowed"] is False, f"Failed to block dangerous command: {cmd}"
        assert res["rule_id"] == expected_rule, f"Expected rule '{expected_rule}', got '{res['rule_id']}'"
        assert "a2ui_card" in res, "Missing A2UI Action Card on blocked command"
        assert res["a2ui_card"]["actions"][0]["action_type"] == "approve"

    print(f"  [PASS] Blocked {len(critical_tests)} critical/destructive commands and generated A2UI cards")

    # 2. Test safe commands allowed
    safe_commands = [
        "git status",
        "nix build .#checks.x86_64-linux.homepage-dashboard-test",
        "ls -la /persist",
        "python3 layers/70-agents/71-harness/news_curator.py --test",
        "clan machines list",
        "echo 'Hello Aperture Science'"
    ]

    for cmd in safe_commands:
        res = guard.inspect_command(cmd, agent_id="test-agent")
        assert res["allowed"] is True, f"Erroneously blocked safe command: {cmd}"
        assert res["verdict"] == "ALLOWED"

    print(f"  [PASS] Successfully passed {len(safe_commands)} safe development commands")

    # 3. Test override approval workflow
    blocked = guard.inspect_command("git push --force origin test-branch", agent_id="hermes")
    card_id = blocked["a2ui_card"]["card_id"]
    assert guard.approve_override(card_id) is True
    print("  [PASS] 1-Tap A2UI override approval workflow verified")

    if test_db.exists():
        test_db.unlink()

    print("==> All Damage Control Guard tests PASSED!")
    return 0

if __name__ == "__main__":
    if "--test" in sys.argv:
        sys.exit(self_test())
    elif "--inspect" in sys.argv:
        idx = sys.argv.index("--inspect")
        if idx + 1 < len(sys.argv):
            cmd = sys.argv[idx + 1]
            guard = DamageControlGuard()
            res = guard.inspect_command(cmd)
            print(json.dumps(res, indent=2))
        else:
            print("Error: --inspect requires a command string")
            sys.exit(1)
    else:
        print("Usage: damage_control.py [--test | --inspect '<command>']")
