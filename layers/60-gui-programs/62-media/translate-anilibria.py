def translate_tree(root_dir: str) -> int:
    patched_files = 0
    # Sort keys longest-first so longer phrases match before substrings
    sorted_pairs = sorted(EXACT_TRANSLATIONS.items(), key=lambda kv: len(kv[0]), reverse=True)

    for dirpath, _, filenames in os.walk(root_dir):
        for fn in filenames:
            if not fn.endswith((".qml", ".cpp", ".h", ".js")):
                continue
            filepath = os.path.join(dirpath, fn)
            try:
                with open(filepath, "r", encoding="utf-8") as f:
                    content = f.read()
            except Exception:
                continue

            original = content
            for ru, en in sorted_pairs:
                for quote in ('"', "'", "`"):
                    content = content.replace(f"{quote}{ru}{quote}", f"{quote}{en}{quote}")

            if content != original:
                with open(filepath, "w", encoding="utf-8") as f:
                    f.write(content)
                patched_files += 1

    return patched_files

if __name__ == "__main__":
    target = sys.argv[1] if len(sys.argv) > 1 else "src"
    count = translate_tree(target)
    print(f"Translated {count} source files in {target}")
